const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const source = fs.readFileSync(path.join(__dirname, '..', 'frontend', 'assets', 'index.js'), 'utf8');
const start = source.indexOf('function selectedEstablishments(');
const end = source.indexOf('\nasync function action(name)', start);
assert(start >= 0 && end > start);
const directory = 'C:\\GeoCNPJ\\2026-11';
const establishment = (name, local = true) => ({name,kind:'establishment',size:100,local:local?{status:'same_month',path:directory+'\\'+name}:{status:'remote'}});
const references = ['Cnaes.zip','Motivos.zip','Municipios.zip','Paises.zip'].map(name=>({name,kind:'reference',size:1,local:{status:'reusable'}}));
const catalog = [establishment('Estabelecimentos0.zip'), establishment('Estabelecimentos1.zip'),...references];
const picks = [{checked:true,dataset:{index:'0'}},{checked:true,dataset:{index:'1'}}];
const button = {dataset:{},getAttribute:()=>null,textContent:'',disabled:false};
const elements={destination:{textContent:directory},selectedSize:{textContent:''},selectionNote:{textContent:''},start:button};
const context={catalog,document:{querySelectorAll:()=>picks},$:id=>elements[id],joinLocal:(base,child)=>base+'\\'+child,fmt:n=>String(n),GeoUI:{}};
vm.createContext(context);vm.runInContext(source.slice(start,end),context);
assert.equal(context.downloadSelectionMode().label,'Conferir arquivos já disponíveis');
context.updateSelection();
assert.equal(button.textContent,'Conferir arquivos já disponíveis');
assert.match(elements.selectionNote.textContent,/2 de 2 partes/);
catalog[1].local={status:'remote'};
assert.equal(context.downloadSelectionMode().label,'Baixar apenas o que falta');
context.updateSelection();
assert.equal(button.textContent,'Baixar apenas o que falta');
catalog[1].local={status:'same_month',path:directory+'\\Estabelecimentos1.zip'};
elements.destination.textContent='D:\\OutroDisco\\2026-11';
assert.equal(context.downloadSelectionMode().label,'Baixar arquivos selecionados');
console.log('Rótulo do pedido distingue arquivos locais, pendentes e outra pasta.');
